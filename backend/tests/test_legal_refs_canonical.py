"""L5: страж дрейфа формулировок статей закона в calculators.py.

Текст законов в калькуляторах намеренно НЕ дедуплицируется (правило «DRY про знание,
не про текст» из CLAUDE.md): прозу-ссылку повторяем осознанно. Остаточный риск —
что одна из ~45 копий ссылки разъедется по формулировке (опечатка в номере/дате
закона уедет в платный документ). Этот тест пинит канонические строки и валит сборку
при появлении неканонического варианта.
"""

import re
from pathlib import Path

_CALC_SRC = (Path(__file__).resolve().parents[1] / "app" / "services" / "calculators.py").read_text(
    encoding="utf-8"
)

# Канонические формы ключевых статутов и сколько раз они должны встречаться как минимум.
_CANONICAL = {
    # ЗоЗПП — закон о защите прав потребителей
    "от 07.02.1992 № 2300-1": 1,
    # ФЗ-214 — долевое строительство
    "от 30.12.2004 № 214-ФЗ": 1,
    # ст. 236 ТК РФ — компенсация за задержку зарплаты
    "ст. 236 ТК РФ": 1,
}

# Неканонические варианты, которые не должны появляться (типичный дрейф формы).
_FORBIDDEN_VARIANTS = [
    r"№2300-1",            # без пробела после №
    r"№214-ФЗ",            # без пробела после №
    r"2300-01",            # лишний ноль в номере
    r"214-Ф3",             # «3» вместо «Ф»-кириллицы / латиницы — частая опечатка
    r"ст\.236 ТК",         # без пробела после «ст.»
    r"07\.02\.1992 ?г\.",  # лишнее «г.» после даты закона
]


def test_canonical_statute_strings_present():
    for canonical, min_count in _CANONICAL.items():
        count = _CALC_SRC.count(canonical)
        assert count >= min_count, f"каноничная ссылка пропала/изменилась: {canonical!r} (найдено {count})"


def test_no_drifted_statute_variants():
    for pattern in _FORBIDDEN_VARIANTS:
        assert not re.search(pattern, _CALC_SRC), f"найден неканоничный вариант ссылки: {pattern!r}"
